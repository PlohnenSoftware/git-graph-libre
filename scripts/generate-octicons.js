// Regenerates src/octicons.ts from the installed @primer/octicons package.
// Run with: pnpm run icons:generate
const fs = require("node:fs");
const path = require("node:path");

// Keep this list alphabetical; it is the single source of truth for which
// octicons ship inside the extension and webview bundles.
const ICON_NAMES = [
  "alert",
  "arrow-down",
  "arrow-up",
  "copy",
  "crosshairs",
  "download",
  "file",
  "file-directory-fill",
  "file-directory-open-fill",
  "gear",
  "git-branch",
  "history",
  "info",
  "link-external",
  "search",
  "sync",
  "tag",
  "verified",
  "x"
];

const data = require("@primer/octicons/build/data.json");

const missing = ICON_NAMES.filter((name) => data[name]?.heights?.["16"] === undefined);
if (missing.length > 0) {
  console.error(`No 16px variant found for octicons: ${missing.join(", ")}`);
  process.exit(1);
}

const escapeTsString = (value) =>
  value.replaceAll("\\", String.raw`\\`).replaceAll("'", String.raw`\'`);

const entries = ICON_NAMES.map((name) => {
  const { width, path: pathMarkup } = data[name].heights["16"];
  return `  "${name}": { width: ${width}, path: '${escapeTsString(pathMarkup)}' }`;
});

const version = require("@primer/octicons/package.json").version;

const output = `// Generated by scripts/generate-octicons.js from @primer/octicons ${version} — do not edit by hand.
// Octicons are © GitHub, Inc. and distributed under the MIT license:
// https://github.com/primer/octicons
export type OcticonName =
${ICON_NAMES.map((name) => `  | "${name}"`).join("\n")};

const octicons: Readonly<Record<OcticonName, { width: number; path: string }>> = {
${entries.join(",\n")}
};

/**
 * Render a 16px octicon as an inline SVG string. Color is inherited from the
 * CSS \`color\` of the surrounding element via \`fill="currentColor"\`, and can
 * be overridden with a CSS \`fill\` rule.
 */
export function octicon(name: OcticonName, className?: string): string {
  const icon = octicons[name];
  const classes = className === undefined ? \`octicon octicon-\${name}\` : \`octicon octicon-\${name} \${className}\`;
  return \`<svg xmlns="http://www.w3.org/2000/svg" class="\${classes}" viewBox="0 0 \${icon.width} 16" width="16" height="16" fill="currentColor" aria-hidden="true">\${icon.path}</svg>\`;
}
`;

const outFile = path.join(__dirname, "..", "src", "octicons.ts");
fs.writeFileSync(outFile, output);
console.log(`Wrote ${ICON_NAMES.length} octicons to ${path.relative(process.cwd(), outFile)}`);
